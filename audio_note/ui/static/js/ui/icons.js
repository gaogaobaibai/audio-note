/**
 * icon("play") / icon("x", 16) / icon("alert", 18, {label: "警告"}).
 * Decorative by default (aria-hidden); with a label it is announced as an image.
 */
export function icon(name, size = 18, { label = "", cls = "" } = {}) {
  const body = ICONS[name] || ICONS.dot;
  const filled = body[0] === "!";
  const inner = filled ? body.slice(1) : body;
  const paint = filled
    ? 'fill="currentColor" stroke="none"'
    : 'fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"';
  const a11y = label ? `role="img" aria-label="${esc(label)}"` : 'aria-hidden="true" focusable="false"';
  const s = Number(size) || 18;
  return new SafeHtml(`<svg class="ic${cls ? ` ${esc(cls)}` : ""}" width="${s}" height="${s}" viewBox="0 0 24 24" ${paint} ${a11y}>${inner}</svg>`);
}
